/**
 * Generates `config/hydrate-defaults.generated.ts` - the folder-derived portion of the
 * declarative-shadow-dom allow-list `config/hydrate-defaults.ts` builds `dsdTags` from. Gitignored
 * (see `.gitignore`) and regenerated on every build, same pattern as
 * `generate-component-tags.mjs`'s `tags.constant.ts`.
 *
 * Every tag under `overlays/`, `navigation/`, and `forms/` renders DSD - interactive/input
 * components, wholesale, versus `scoped` for everything presentational/layout. That includes
 * high-count simple controls (`ds-checkbox`, `ds-input`, …) that would benefit more from
 * `scoped`'s shared-stylesheet savings than the overlay/positioning components this list
 * originally targeted - a deliberate simplicity-over-byte-count tradeoff.
 *
 * A handful of components outside those three folders are DSD too - hand-listed in
 * `hydrate-defaults.ts`'s `handCuratedDsdTags`, not globbed here, because they don't share a
 * folder boundary with each other. See that array's doc comment for the two-criteria test
 * (teleport/positioning behavior, or typically low per-page usage count) that decides whether a
 * component belongs there. See also docs/adr/0034-ssr-mixed-serialize-shadow-root.md.
 */
import fg from 'fast-glob'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const AUTO_DSD_GLOBS = [
  { label: 'overlays/*', pattern: 'src/components/overlays/**/*.tsx' },
  { label: 'navigation/*', pattern: 'src/components/navigation/**/*.tsx' },
  { label: 'forms/*', pattern: 'src/components/forms/**/*.tsx' },
]

async function tagsForGlob(coreRoot, pattern) {
  const files = await fg(pattern, {
    cwd: coreRoot,
    ignore: ['**/*.data.tsx', '**/field.util.tsx', '**/*.interfaces.tsx', '**/index.tsx', '**/test/**'],
  })
  const tags = await Promise.all(
    files.map(async f => {
      const src = await readFile(resolve(coreRoot, f), 'utf-8')
      const m = src.match(/tag:\s*['"`]([^'"`]+)['"`]/)
      return m ? m[1] : null
    }),
  )
  return tags.filter(t => !!t).sort()
}

export async function generateHydrateDefaultsTags(coreRoot) {
  const groups = await Promise.all(
    AUTO_DSD_GLOBS.map(async ({ label, pattern }) => ({ label, tags: await tagsForGlob(coreRoot, pattern) })),
  )

  const body = groups.map(({ label, tags }) => `  // ${label}\n${tags.map(t => `  '${t}',`).join('\n')}`).join('\n\n')

  await mkdir(resolve(coreRoot, 'config'), { recursive: true })
  await writeFile(
    resolve(coreRoot, 'config/hydrate-defaults.generated.ts'),
    `// This file is auto-generated by scripts/build-core.mjs - do not edit manually\n\nexport const autoDsdTags: string[] = [\n${body}\n]\n`,
  )

  return groups.flatMap(({ tags }) => tags)
}
