/**
 * Generates `packages/angular/src/generated/meta.ts` — a `<Component>Inputs` / `<Component>Outputs`
 * constant per component, extracted from the `inputs`/`outputs` arrays that `@stencil/angular-output-target`
 * already writes into `packages/angular/src/generated/proxies.ts`.
 *
 * Angular form wrapper components (see `packages/angular/src/forms/`) re-declare `inputs`/`outputs` on their
 * own `@Component` decorator — Angular's compiler resolves them statically and can't inherit them from a
 * parent class. Importing these generated constants instead of hand-listing every prop keeps that
 * declaration in sync with the underlying Stencil component automatically.
 *
 * Run as part of `pnpm --filter @baloise/ds-core build`, after Stencil has (re)written proxies.ts.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const proxiesFile = resolve(__dirname, '../../angular/src/generated/proxies.ts')
const metaFile = resolve(__dirname, '../../angular/src/generated/meta.ts')

export async function generateAngularMeta() {
  const source = await readFile(proxiesFile, 'utf-8')

  // Each component is wrapped in its own `@ProxyCmp({ ... }) @Component({ ... }) export class Xyz { ... }`
  // block; split on `@ProxyCmp(` so every chunk below contains exactly one component's decorators.
  const chunks = source.split('@ProxyCmp(').slice(1)

  const components = chunks.map(chunk => {
    const className = chunk.match(/export class (\w+)/)?.[1]
    const inputs = chunk.match(/inputs:\s*(\[[^\]]*\])/)?.[1] ?? '[]'
    const outputs = chunk.match(/outputs:\s*(\[[^\]]*\])/)?.[1] ?? '[]'
    return { className, inputs, outputs }
  })

  const missingClassName = components.find(c => !c.className)
  if (missingClassName) {
    throw new Error('generate-angular-meta: could not find a class name for a @ProxyCmp block in proxies.ts')
  }

  const body = components
    .map(
      ({ className, inputs, outputs }) =>
        // No `as const`: Angular's `@Component({ inputs, outputs })` types expect mutable `string[]`.
        `export const ${className}Inputs: string[] = ${inputs}\nexport const ${className}Outputs: string[] = ${outputs}`,
    )
    .join('\n\n')

  await writeFile(
    metaFile,
    `// This file is auto-generated by generate-angular-meta.mjs from proxies.ts - do not edit manually\n\n${body}\n`,
  )

  console.log(`\x1b[32m✔\x1b[0m Generated Angular meta for ${components.length} components`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateAngularMeta().catch(err => {
    console.error('✗ generate-angular-meta failed:', err)
    process.exit(1)
  })
}
